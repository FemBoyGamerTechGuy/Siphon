#!/usr/bin/env python3
"""Generate src/unicode_tables.c for Siphon (dev-time tool, not used by
the build or runtime).

Produces a sorted, non-overlapping range table mapping codepoint ranges
to classification flags. The classification mirrors the properties the
tokenizer needs from the reference implementation (llama.cpp):

  LETTER     - Unicode category L*            (regex \\p{L})
  NUMBER     - Unicode category N*            (regex \\p{N})
  WHITESPACE - explicit set (see below)       (regex \\s equivalent)
  DEFINED    - any assigned codepoint          (nonzero flags)

The whitespace set is the exact list used by the reference tokenizer
(the regex \\s of Python's `re`, which the reference mirrors):
  0009-000D, 0020, 0085, 00A0, 1680, 2000-200A, 2028, 2029, 202F, 205F, 3000

Run:  python3 scripts/gen_unicode_tables.py > src/unicode_tables.c
"""
import sys
import unicodedata

WHITESPACE = sorted({
    0x0009, 0x000A, 0x000B, 0x000C, 0x000D, 0x0020, 0x0085, 0x00A0,
    0x1680, 0x2000, 0x2001, 0x2002, 0x2003, 0x2004, 0x2005, 0x2006,
    0x2007, 0x2008, 0x2009, 0x200A, 0x2028, 0x2029, 0x202F, 0x205F,
    0x3000,
})

F_LETTER = 1
F_NUMBER = 2
F_WHITESPACE = 4

MAX_CP = 0x110000

WHITESPACE_SET = set(WHITESPACE)


def main() -> None:
    ranges = []  # [start, end_inclusive, flags]
    cur_start, cur_flags = 0, -1

    def flush(end_inclusive: int) -> None:
        nonlocal cur_start, cur_flags
        if cur_flags != 0 and cur_start <= end_inclusive:
            ranges.append((cur_start, end_inclusive, cur_flags))

    for cp in range(MAX_CP):
        f = 0
        cat = unicodedata.category(chr(cp))
        if cat != "Cn":
            f |= 8  # DEFINED
        if cat.startswith("L"):
            f |= F_LETTER
        if cat.startswith("N"):
            f |= F_NUMBER
        if cp in WHITESPACE_SET:
            f |= F_WHITESPACE
        if f != cur_flags:
            flush(cp - 1)
            cur_start, cur_flags = cp, f
    flush(MAX_CP - 1)

    print("/* Generated by scripts/gen_unicode_tables.py — DO NOT EDIT.")
    print(" * Unicode categories via Python unicodedata (Unicode "
          + unicodedata.unidata_version + ").")
    print(" * Semantics mirror the reference tokenizer's tables")
    print(" * (letters \\p{L}, numbers \\p{N}, whitespace set, definedness).")
    print(" * Ranges are sorted, non-overlapping; unlisted codepoints are")
    print(" * undefined. Flags: 1=letter 2=number 4=whitespace 8=defined. */")
    print()
    print('#include "siphon/unicode.h"')
    print()
    print("const si_uni_range si_uni_ranges[] = {")
    for start, end, f in ranges:
        print(f"    {{0x{start:06X}, 0x{end:06X}, {f}}},")
    print("};")
    print()
    print(f"const uint32_t si_uni_ranges_n = {len(ranges)};")


if __name__ == "__main__":
    main()
